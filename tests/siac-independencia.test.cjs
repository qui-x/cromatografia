"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const index=read("index.html"),style=read("css/investigacao.css"),pwa=read("js/init/pwa.js"),sw=read("sw.js");
const core=read("js/core/namespace.js"),maker=read("build_standalone.py");
const pack=JSON.parse(read("package.json")),lock=JSON.parse(read("package-lock.json"));
for(const legacy of ["FILES.txt","SHA256SUMS.txt","SHA512SUMS.txt"]){
 assert(!fs.existsSync(path.join(root,legacy)),legacy+" deve sair da raiz");
 assert(fs.existsSync(path.join(root,"docs/legado-siab/distribuicao",legacy)),legacy+" deve ficar preservado no arquivo histórico");
}
assert.doesNotMatch(index,/\?v=1\.0\.0|Sobre o SIAB|Simulador de Indicadores Ácido-Base/);
assert.match(index,/<h2 id="about-title">Sobre o SIAC<\/h2>/);
assert.match(index,/frações cromatográficas/);
assert(!/radial-gradient\(ellipse at 100% 0,\s*#c026d3/i.test(style),"Fundo violeta legado presente");
assert(!/drop-shadow\([^)]*#c026d3/i.test(style),"Sombra violeta legada presente");
assert.match(style,/\.inicio-caminhos \.caminho-laboratorio\s*\{[\s\S]*?background: var\(--panel\);/);
assert.match(core,/window\.SIAC = Object\.assign/);
assert.match(core,/window\.SIAB = window\.SIAC;/);
assert.match(core,/version: "0\.2\.0-dev\.0"/);
assert.match(pwa,/Nova versão do SIAC instalada/);
assert.match(pwa,/SIAC instalado\./);
assert.doesNotMatch(pwa,/"siab@"|c\.indexOf\("siab@"\)/);
assert.match(pwa,/r\.scope === new URL\("\.\/", location\.href\)\.href/);
assert.match(sw,/const VERSAO = "siac-v0\.2\.0-dev-[^"]+";/);
assert.doesNotMatch(sw,/Service worker do SIAB/);
assert.match(maker,/f'SIAC-\{versao\}-standalone\.html'/);
assert.doesNotMatch(maker,/f'SIAB-\{versao\}-standalone\.html'/);
assert.equal(pack.version,"0.2.0-dev.0");
assert.equal(lock.version,pack.version);
assert.equal(lock.packages[""].version,pack.version);
assert.match(pack.description,/SIAC/);
console.log("SIAC: card sem halo violeta, páginas/versões limpas, PWA e standalone SIAC isolados.");
