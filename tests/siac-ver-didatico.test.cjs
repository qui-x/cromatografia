"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const catalog=require("../js/data/siac-catalogo-contextual.js");
const ver=require("../js/ui/siac-ver-didatico.js");
const metrics=require("../js/simulation/siac-metricas.js");
const sel=id=>({substanciaId:id,sistemaId:catalog.sistemasPara(id)[0]?.id||"",
  substancia:catalog.substancia(id),sistema:catalog.sistemasPara(id)[0]||null});
let tela=ver.render(sel("glycine"),metrics);
assert.match(tela.contexto,/Glicina/);
assert.equal((tela.modulos.match(/data-module=/g)||[]).length,3);
assert.match(tela.itens,/Ninhidrina/);
assert(ver.setFerramenta("ninhidrina"));
tela=ver.render(sel("glycine"),metrics);
assert.match(tela.conteudo,/Técnica descrita no método/);
assert(ver.evidencia(sel("glycine").sistema,"ninhidrina"));
assert(ver.setFerramenta("uv254"));
tela=ver.render(sel("glycine"),metrics);
assert.match(tela.conteudo,/Técnica não confirmada/);
assert.match(tela.itens,/UV 254 · guia/);
assert(ver.setModulo("medir"));
assert(ver.setFerramenta("regua"));
tela=ver.render(sel("glycine"),metrics);
assert.match(tela.conteudo,/data-siac-medicao="frente"/);
assert.equal(ver.calcular(metrics).ok,false);
assert(ver.setMedicao("frente","50"));
assert(ver.setMedicao("mancha","10"));
assert.equal(ver.validar().ok,true);
assert(ver.setModulo("calcular"));
assert(ver.setFerramenta("rf"));
const calc=ver.calcular(metrics);
assert(calc.ok);
assert.equal(calc.rf,0.2);
assert.equal(calc.evidencia,"exercicio_de_leitura_sem_observacao_instrumentada");
tela=ver.render(sel("glycine"),metrics);
assert.match(tela.conteudo,/Rf do exercício/);
assert.match(tela.conteudo,/0,2/);
assert(ver.setFerramenta("comparar"));
tela=ver.render(sel("glycine"),metrics);
assert.match(tela.conteudo,/Diferença absoluta/);
assert.match(tela.conteudo,/não confirma identidade/);
assert(ver.setFerramenta("coluna"));
assert.match(ver.render(sel("glycine"),metrics).conteudo,/não pode ser convertido automaticamente/);
assert(ver.setModulo("medir"));
assert(ver.setFerramenta("regua"));
assert(ver.setMedicao("frente","50"));
assert(ver.setMedicao("mancha","60"));
assert.equal(ver.calcular(metrics).ok,false,"mancha além da frente não pode produzir Rf");
const clean=ver.render(sel("caffeine"),metrics);
assert.match(clean.conteudo,/não há retenção ou detector/);
assert.equal(ver.snapshot.frente,"","troca de substância deve apagar medidas");
assert.equal(ver.snapshot.mancha,"");
const similar=ver.render(sel("tartrazina"),metrics);
assert.match(similar.conteudo,/O protocolo é referência bibliográfica/);
ver.setModulo("calcular");ver.setFerramenta("comparar");
assert.match(ver.render(sel("tartrazina"),metrics).conteudo,/não oferece Rf individual/);
assert(!ver.setModulo("fake"),"módulos desconhecidos não podem criar controles inertes");
assert(!ver.setFerramenta("fake"));
const html=fs.readFileSync(path.join(__dirname,"../index.html"),"utf8");
for(const script of ["js/simulation/siac-metricas.js","js/ui/siac-ver-didatico.js"])
 assert(html.includes(script),"script não carregado: "+script);
assert(html.indexOf("siac-ver-didatico.js")<html.indexOf("siac-laboratorio-integrado.js"));
console.log("SIAC Ver: observar, medir e calcular; referência, detector, Rf e restrições de coluna — OK");
